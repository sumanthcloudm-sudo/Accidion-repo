"""Build the self-contained Bash launcher from the editable kit files."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAYLOAD = (
    "starter_kit.py", "starter_install.py", "starter_findings.py",
    "python-bootstrap.sh", ".gitleaks.toml", "semgrep.yml", ".checkov.yml",
    "accidion-dependencies.gradle",
)


PREVIEW = r'''preview_payload() {
  "${python_cmd[@]}" -E -s -B -c '
import sys
from pathlib import Path
from types import ModuleType

launcher = Path(sys.argv.pop(1))
source = launcher.read_text(encoding="utf-8")
for name in ("starter_install", "starter_findings", "starter_kit"):
    quote = chr(39)
    prefix = "  command cat > " + chr(34) + "$1/" + name + ".py" + chr(34) + " <<" + quote
    _, found, component = source.partition(prefix)
    marker, opened, payload = component.partition(quote + "\n")
    code, closed, _ = payload.partition("\n" + marker + "\n")
    if not (found and opened and closed):
        raise SystemExit("Embedded preview component missing: " + name)
    module = ModuleType(name)
    module.__file__ = str(launcher.parent / (name + ".py"))
    sys.modules[name] = module
    exec(compile(code, module.__file__, "exec"), module.__dict__)
raise SystemExit(module.main(in_memory_preview=True))
' "$launcher" "$@"
}'''


def build():
    launcher = (ROOT / "security-scan.sh").read_text(encoding="utf-8")
    _, body = launcher.split("\n", 1)
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by scripts/build_standalone.py. Edit the source kit and rebuild.",
        "extract_payload() {",
    ]
    for name in PAYLOAD:
        content = (ROOT / name).read_text(encoding="utf-8")
        digest = hashlib.sha256(content.encode("utf-8")).hexdigest()
        delimiter = f"ACCIDION_{digest}"
        if delimiter in content.splitlines():
            raise ValueError(f"Payload delimiter collision in {name}")
        lines.extend((f"""  command cat > "$1/{name}" <<'{delimiter}'""",
                      content.removesuffix("\n"), delimiter))
    lines.extend(("}", "", PREVIEW, "", body))
    return "\n".join(lines).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the distribution needs rebuilding")
    args = parser.parse_args()
    output = ROOT / "dist" / "security-scan.sh"
    generated = build()
    if args.check:
        if not output.is_file() or output.read_bytes() != generated:
            parser.exit(1, "Run python scripts/build_standalone.py to refresh dist/security-scan.sh\n")
    else:
        output.parent.mkdir(exist_ok=True)
        output.write_bytes(generated)
        output.chmod(0o755)


if __name__ == "__main__":
    main()
